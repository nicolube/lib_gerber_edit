coord_scaling!(CoordinateOffset);

/// Operation coordinates of `cmd`, if it is a D01/D02/D03 carrying any.
fn operation_coords(cmd: &mut Command) -> Option<&mut Coordinates> {
    match cmd {
        Command::FunctionCode(FunctionCode::DCode(DCode::Operation(
            Operation::Move(Some(coords))
            | Operation::Flash(Some(coords))
            | Operation::Interpolate(Some(coords), _),
        ))) => Some(coords),
        _ => None,
    }
}

/// Writes both axes of every operation as absolute coordinates.
///
/// Gerber coordinates are modal (an omitted axis keeps its previous value) and
/// may be incremental (`FS..I..`). Resolving both on load means transforms,
/// merges and step-and-repeat never depend on earlier commands or on the mode.
/// Arc I/J offsets are relative in both modes and stay as-is.
fn resolve_operation_coords(commands: &mut [Command], incremental: bool) {
    let (mut x, mut y) = (0.0, 0.0);
    for cmd in commands.iter_mut() {
        if let Some(coords) = operation_coords(cmd) {
            let axis = |v: Option<CoordinateNumber>, cur: f64| match v {
                Some(v) if incremental => cur + f64::from(v),
                Some(v) => f64::from(v),
                None => cur,
            };
            (x, y) = (axis(coords.x, x), axis(coords.y, y));
            coords.x = CoordinateNumber::try_from(x).ok();
            coords.y = CoordinateNumber::try_from(y).ok();
        }
    }
}

/// Rotates `coords` by `rotation_steps` CW quarter-turns about the origin and then
/// translates by `(dx, dy)`.
///
/// `current` is the modal current point before this operation (pre-transform).
/// Gerber coordinates are modal: an omitted axis keeps its previous value. A pure
/// translation keeps omitted axes omitted (they inherit an already shifted value),
/// but a rotation mixes both axes, so the omitted one is filled in from `current`
/// and both are written.
fn rotate_and_translate_coords(
    coords: &mut Coordinates,
    current: &mut (f64, f64),
    dx: f64,
    dy: f64,
    rotation_steps: i32,
) {
    let x = coords.x.map(f64::from).unwrap_or(current.0);
    let y = coords.y.map(f64::from).unwrap_or(current.1);
    *current = (x, y);
    if rotation_steps != 0 {
        let (rx, ry) = crate::rotate_90(x, y, rotation_steps);
        coords.x = CoordinateNumber::try_from(rx + dx).ok();
        coords.y = CoordinateNumber::try_from(ry + dy).ok();
    } else {
        if coords.x.is_some() {
            coords.x = CoordinateNumber::try_from(x + dx).ok();
        }
        if coords.y.is_some() {
            coords.y = CoordinateNumber::try_from(y + dy).ok();
        }
    }
}

/// Rotate an arc's I/J center offset by `rot` CW quarter-turns. Writes both
/// components even when one was None: a `J5` half-circle rotated 90° must
/// land as `I5J0`, not silently drop the new I.
fn rotate_arc_ij_offset(ij: &mut Option<CoordinateOffset>, rot: i32) {
    if rot == 0 {
        return;
    }
    let Some(off) = ij else {
        return;
    };
    let i = off.x.map(f64::from).unwrap_or(0.0);
    let j = off.y.map(f64::from).unwrap_or(0.0);
    let (ri, rj) = crate::rotate_90(i, j, rot);
    if let Ok(v) = CoordinateNumber::try_from(ri) {
        off.x = Some(v);
    }
    if let Ok(v) = CoordinateNumber::try_from(rj) {
        off.y = Some(v);
    }
}

fn rotate_step_and_repeat(
    distance_x: &mut f64,
    distance_y: &mut f64,
    repeat_x: &mut u32,
    repeat_y: &mut u32,
    rot: i32,
) {
    let (sx, sy) = crate::rotate_90(*distance_x, 0.0, rot);
    let (tx, ty) = crate::rotate_90(0.0, *distance_y, rot);
    if rot % 2 == 1 {
        *distance_x = tx;
        *distance_y = sy;
        std::mem::swap(repeat_x, repeat_y);
    } else {
        *distance_x = sx;
        *distance_y = ty;
    }
}

fn rebase_gerber_commands(commands: &mut [Command], rot: i32, dx: f64, dy: f64) {
    let mut current = (0.0, 0.0);
    for cmd in commands.iter_mut() {
        match cmd {
            Command::FunctionCode(FunctionCode::DCode(DCode::Operation(
                Operation::Move(Some(coords)) | Operation::Flash(Some(coords)),
            ))) => {
                rotate_and_translate_coords(coords, &mut current, dx, dy, rot);
            }
            Command::FunctionCode(FunctionCode::DCode(DCode::Operation(
                Operation::Interpolate(Some(coords), ij),
            ))) => {
                rotate_and_translate_coords(coords, &mut current, dx, dy, rot);
                rotate_arc_ij_offset(ij, rot);
            }
            Command::ExtendedCode(ExtendedCode::StepAndRepeat(StepAndRepeat::Open {
                distance_x,
                distance_y,
                repeat_x,
                repeat_y,
            })) if rot != 0 => {
                rotate_step_and_repeat(distance_x, distance_y, repeat_x, repeat_y, rot);
            }
            _ => {}
        }
    }
}

fn rotate_gerber_apertures(apertures: &mut std::collections::HashMap<i32, Aperture>, rot: i32) {
    if rot == 0 {
        return;
    }
    let odd = rot % 2 == 1;
    let degrees_ccw_delta = -90.0 * rot as f64;
    for ap in apertures.values_mut() {
        match ap {
            Aperture::Circle(_) => {}
            Aperture::Rectangle(r) | Aperture::Obround(r) => {
                if odd {
                    std::mem::swap(&mut r.x, &mut r.y);
                }
            }
            Aperture::Polygon(p) => {
                let cur = p.rotation.unwrap_or(0.0);
                p.rotation = Some(cur + degrees_ccw_delta);
            }
            // Rotated through their macro bodies, see `rotate_gerber_macros`.
            Aperture::Macro(_, _) => {}
        }
    }
}

/// `-90`, `+180`: `value` with an explicit sign for appending to an expression.
fn signed(value: f64) -> String {
    if value < 0.0 {
        format!("-{}", -value)
    } else {
        format!("+{value}")
    }
}

/// Folds `delta` into an expression of the form `(<inner>)±k` (as written
/// by an earlier rotation), keeping the offset within one turn.
fn fold_rotation(expr: &str, delta: f64) -> Option<String> {
    let close = expr.rfind(')')?;
    let inner = expr.strip_prefix('(')?.get(..close - 1)?;
    // `inner` must be one bracketed term, not `a)+(b` from `(a)+(b)-90`.
    let balanced = inner.chars().try_fold(0i32, |depth, c| match c {
        '(' => Some(depth + 1),
        ')' => (depth > 0).then(|| depth - 1),
        _ => Some(depth),
    }) == Some(0);
    if !balanced {
        return None;
    }
    let offset: f64 = expr[close + 1..].trim_start_matches('+').parse().ok()?;
    let total = (offset + delta).rem_euclid(360.0);
    Some(if total == 0.0 {
        inner.to_string()
    } else {
        format!("({inner}){}", signed(total - 360.0))
    })
}

/// Rotates every macro by `rot` CW quarter-turns by adding the angle to each
/// primitive's rotation parameter (primitives rotate about the macro
/// origin, i.e. the flash point). All apertures of a layer rotate together,
/// so the macro bodies are changed in place.
fn rotate_gerber_macros(macros: &mut HashMap<String, Vec<MacroContent>>, rot: i32) {
    if rot == 0 {
        return;
    }
    let delta = -90.0 * rot as f64;
    let add = |angle: &mut MacroDecimal| {
        *angle = match angle {
            // Fold an offset added by an earlier rotation, so repeated
            // rotations do not nest expressions.
            MacroDecimal::Expression(e) => match fold_rotation(e, delta) {
                Some(folded) => MacroDecimal::Expression(folded),
                None => map_macro_decimal(angle, |v| v + delta, &signed(delta)),
            },
            _ => map_macro_decimal(angle, |v| v + delta, &signed(delta)),
        };
    };
    for content in macros.values_mut().flatten() {
        match content {
            MacroContent::Circle(c) => add(c.angle.get_or_insert(MacroDecimal::Value(0.0))),
            MacroContent::VectorLine(p) => add(&mut p.angle),
            MacroContent::CenterLine(p) => add(&mut p.angle),
            MacroContent::Outline(p) => add(&mut p.angle),
            MacroContent::Polygon(p) => add(&mut p.angle),
            MacroContent::Moire(p) => add(&mut p.angle),
            MacroContent::Thermal(p) => add(&mut p.angle),
            MacroContent::VariableDefinition(_) | MacroContent::Comment(_) => {}
        }
    }
}

impl LayerRotate for GerberLayerData {
    fn rotate(&mut self, steps: i32) {
        let steps = steps.rem_euclid(4);
        if steps == 0 {
            return;
        }
        let (min, max) = self.get_corners();
        let cx = (min.x + max.x) * 0.5;
        let cy = (min.y + max.y) * 0.5;
        let (rcx, rcy) = crate::rotate_90(cx, cy, steps);
        self.rebase(
            steps,
            &Pos {
                x: cx - rcx,
                y: cy - rcy,
            },
        );
    }

    fn rebase(&mut self, steps: i32, offset: &Pos) {
        let steps = steps.rem_euclid(4);
        rebase_gerber_commands(&mut self.commands, steps, offset.x, offset.y);
        rotate_gerber_apertures(&mut self.apertures, steps);
        rotate_gerber_macros(&mut self.macros, steps);
    }
}

impl LayerStepAndRepeat for (&Unit, &mut Vec<Command>) {
    fn step_and_repeat(&mut self, x_repetitions: u32, y_repetitions: u32, offset: &Pos) {
        let sr = Command::ExtendedCode(ExtendedCode::StepAndRepeat(StepAndRepeat::Open {
            repeat_x: x_repetitions,
            repeat_y: y_repetitions,
            distance_x: offset.x.mm_to_unit(self.0),
            distance_y: offset.y.mm_to_unit(self.0),
        }));

        let commands = &mut self.1;
        commands.insert(0, sr);
        // We do this because Avion is stupid and does not update their software...
        // Well for some reason they do not interpret SR close correctly so we put a 1x1 SR here
        // witch results in the same behavior then SR close.
        const SR_RESET_DUMMY: Command =
            Command::ExtendedCode(ExtendedCode::StepAndRepeat(StepAndRepeat::Open {
                repeat_x: 1,
                repeat_y: 1,
                distance_x: 0f64,
                distance_y: 0f64,
            }));
        commands.push(SR_RESET_DUMMY);
        commands.push(Command::ExtendedCode(ExtendedCode::StepAndRepeat(
            StepAndRepeat::Close,
        )))
    }
}

