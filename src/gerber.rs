impl LayerMerge for GerberLayerData {
    /// Appends `other` (converted to this layer's unit).
    ///
    /// Macros are merged by body: an identical body is reused, a name clash
    /// with a different body is renamed to `<name>_<n>`. Apertures (and
    /// aperture-block codes) are deduplicated or moved to free D-codes. The
    /// appended part starts from reset graphics state (G01, dark polarity,
    /// G75 / LM / LR / LS when the receiver changed them). Fails without
    /// changes when either side ends inside an open region or aperture
    /// block.
    fn check_merge(&self, other: &Self) -> Result<(), MergeError> {
        if self.is_negative() != other.is_negative() {
            return Err(MergeError::ImagePolarityMismatch);
        }
        for (commands, side) in [
            (&self.commands, MergeSide::Receiver),
            (&other.commands, MergeSide::Source),
        ] {
            let state = EndState::of(commands);
            if state.open_region {
                return Err(MergeError::OpenRegion(side));
            }
            if state.open_blocks > 0 {
                return Err(MergeError::OpenBlock(side));
            }
        }
        Ok(())
    }

    fn merge(&mut self, other: &Self) -> Result<(), MergeError> {
        self.check_merge(other)?;
        // Nothing below fails, so `self` is mutated directly.
        let mine = EndState::of(&self.commands);
        let other: std::borrow::Cow<Self> = if other.unit == self.unit {
            std::borrow::Cow::Borrowed(other)
        } else {
            std::borrow::Cow::Owned(other.clone().to_unit(&self.unit))
        };
        let macros = &mut self.macros;

        // Macros: reuse identical bodies, rename clashing names.
        let mut macro_names: HashMap<String, String> = HashMap::new();
        let mut names: Vec<_> = other.macros.keys().collect();
        names.sort();
        for name in names {
            let body = &other.macros[name];
            let target = match macros.iter().find(|(_, b)| *b == body) {
                Some((existing, _)) => existing.clone(),
                None => {
                    let mut target = name.clone();
                    let mut n = 0;
                    while macros.contains_key(&target) {
                        n += 1;
                        target = format!("{name}_{n}");
                    }
                    macros.insert(target.clone(), body.clone());
                    target
                }
            };
            macro_names.insert(name.clone(), target);
        }

        // Apertures and aperture-block codes.
        let apertures = &mut self.apertures;
        let mut used: HashSet<i32> = apertures.keys().copied().collect();
        used.extend(block_codes(&self.commands));
        let mut next_code = 10;
        let mut codes: HashMap<i32, i32> = HashMap::new();
        let mut ids: Vec<_> = other.apertures.keys().copied().collect();
        ids.sort();
        for id in ids {
            let mut aperture = other.apertures[&id].clone();
            if let Aperture::Macro(name, _) = &mut aperture
                && let Some(target) = macro_names.get(name)
            {
                *name = target.clone();
            }
            let code = match apertures.iter().find(|(_, a)| **a == aperture) {
                Some((code, _)) => *code,
                None => {
                    let code = next_free(&mut used, &mut next_code);
                    apertures.insert(code, aperture);
                    code
                }
            };
            codes.insert(id, code);
        }
        let mut blocks: Vec<_> = block_codes(&other.commands).collect();
        blocks.sort();
        for code in blocks {
            codes.insert(code, next_free(&mut used, &mut next_code));
        }

        // Seam: the appended commands start from the default graphics state.
        let mut appended = vec![Command::FunctionCode(FunctionCode::GCode(
            GCode::InterpolationMode(InterpolationMode::Linear),
        ))];
        if mine.clear_polarity {
            appended.push(ExtendedCode::LoadPolarity(Polarity::Dark).into());
        }
        if mine.single_quadrant {
            appended.push(GCode::QuadrantMode(QuadrantMode::Multi).into());
        }
        if mine.load_transform {
            appended.push(ExtendedCode::LoadMirroring(Mirroring::None).into());
            appended.push(ExtendedCode::LoadRotation(Rotation { rotation: 0.0 }).into());
            appended.push(ExtendedCode::LoadScaling(Scaling { scale: 1.0 }).into());
        }
        for command in &other.commands {
            let mut command = command.clone();
            if let Some(coords) = operation_coords(&mut command) {
                coords.format = self.coordinate_format;
            }
            match &mut command {
                Command::FunctionCode(FunctionCode::DCode(DCode::SelectAperture(id))) => {
                    if let Some(code) = codes.get(id) {
                        *id = *code;
                    }
                }
                Command::ExtendedCode(ExtendedCode::ApertureBlock(ApertureBlock::Open {
                    code,
                })) => {
                    if let Some(new) = codes.get(code) {
                        *code = *new;
                    }
                }
                Command::FunctionCode(FunctionCode::DCode(DCode::Operation(
                    Operation::Interpolate(_, Some(offset)),
                ))) => offset.format = self.coordinate_format,
                _ => {}
            }
            appended.push(command);
        }

        self.commands.extend(appended);
        self.parse_errors.extend(other.parse_errors.iter().cloned());
        Ok(())
    }
}

/// The lowest D-code from `next` up that is not in `used`; marks it used.
fn next_free(used: &mut HashSet<i32>, next: &mut i32) -> i32 {
    while used.contains(next) {
        *next += 1;
    }
    used.insert(*next);
    *next
}

/// Graphics state at the end of a command list that matters for appending.
#[derive(Default)]
struct EndState {
    open_region: bool,
    open_blocks: usize,
    clear_polarity: bool,
    single_quadrant: bool,
    /// Any LM / LR / LS command was used.
    load_transform: bool,
}

impl EndState {
    fn of(commands: &[Command]) -> Self {
        let mut state = EndState::default();
        for command in commands {
            match command {
                Command::FunctionCode(FunctionCode::GCode(GCode::RegionMode(open))) => {
                    state.open_region = *open
                }
                Command::FunctionCode(FunctionCode::GCode(GCode::QuadrantMode(q))) => {
                    state.single_quadrant = *q == QuadrantMode::Single
                }
                Command::ExtendedCode(ExtendedCode::LoadPolarity(p)) => {
                    state.clear_polarity = *p == Polarity::Clear
                }
                Command::ExtendedCode(ExtendedCode::ApertureBlock(ApertureBlock::Open {
                    ..
                })) => state.open_blocks += 1,
                Command::ExtendedCode(ExtendedCode::ApertureBlock(ApertureBlock::Close)) => {
                    state.open_blocks = state.open_blocks.saturating_sub(1)
                }
                Command::ExtendedCode(
                    ExtendedCode::LoadMirroring(_)
                    | ExtendedCode::LoadRotation(_)
                    | ExtendedCode::LoadScaling(_),
                ) => state.load_transform = true,
                _ => {}
            }
        }
        state
    }
}

/// D-codes defined by aperture blocks (`%ABD<n>*%`).
fn block_codes(commands: &[Command]) -> impl Iterator<Item = i32> + '_ {
    commands.iter().filter_map(|c| match c {
        Command::ExtendedCode(ExtendedCode::ApertureBlock(ApertureBlock::Open { code })) => {
            Some(*code)
        }
        _ => None,
    })
}

impl LayerStepAndRepeat for GerberLayerData {
    fn step_and_repeat(&mut self, x_repetitions: u32, y_repetitions: u32, offset: &Pos) {
        (&self.unit, &mut self.commands).step_and_repeat(x_repetitions, y_repetitions, offset);
    }
}

fn cmd_into_coords(command: &Command) -> Option<&Coordinates> {
    if let Command::FunctionCode(FunctionCode::DCode(DCode::Operation(
        Operation::Move(Some(coords))
        | Operation::Flash(Some(coords))
        | Operation::Interpolate(Some(coords), _),
    ))) = command
    {
        Some(coords)
    } else {
        None
    }
}

/// Updates a position in-place from modal coordinates (omitted axis keeps its current value).
fn update_pos(pos: &mut Pos, coords: &Coordinates, unit: &Unit) {
    if let Some(x) = coords.x {
        pos.x = f64::from(x.to_mm(unit));
    }
    if let Some(y) = coords.y {
        pos.y = f64::from(y.to_mm(unit));
    }
}

/// Returns the bounding box of a circular arc.
///
/// `offset` is the I/J vector from `start` to the arc center (signed for
/// G75, unsigned magnitudes for G74).
fn arc_corners(
    start: &Pos,
    end: &Pos,
    offset: &CoordinateOffset,
    unit: &Unit,
    mode: InterpolationMode,
    quadrant: QuadrantMode,
) -> (Pos, Pos) {
    let i = offset.x.map(|v| f64::from(v.to_mm(unit))).unwrap_or(0.0);
    let j = offset.y.map(|v| f64::from(v.to_mm(unit))).unwrap_or(0.0);

    let [cx, cy] = match quadrant {
        QuadrantMode::Multi => [start.x + i, start.y + j],
        QuadrantMode::Single => crate::flatten::geom::single_quadrant_center(
            [start.x, start.y],
            [end.x, end.y],
            i.abs(),
            j.abs(),
            mode == InterpolationMode::CounterclockwiseCircular,
        )
        .unwrap_or([start.x + i, start.y + j]),
    };
    let ([x0, y0], [x1, y1]) = crate::flatten::geom::arc_bounds(
        [start.x, start.y],
        [end.x, end.y],
        [cx, cy],
        mode == InterpolationMode::CounterclockwiseCircular,
    );
    (Pos { x: x0, y: y0 }, Pos { x: x1, y: y1 })
}

impl LayerCorners for (&Unit, &Vec<Command>) {
    fn get_corners(&self) -> (Pos, Pos) {
        let (unit, cmds) = self;
        let mut min = Pos {
            x: f64::MAX,
            y: f64::MAX,
        };
        let mut max = Pos {
            x: f64::MIN,
            y: f64::MIN,
        };
        for command in cmds.iter() {
            if let Some(coords) = cmd_into_coords(command) {
                min_max(&mut min, &mut max, coords, unit, &None);
            }
        }
        (min, max)
    }
}

impl LayerCorners for GerberLayerData {
    fn get_corners(&self) -> (Pos, Pos) {
        let unit = &self.unit;
        let mut min = Pos {
            x: f64::MAX,
            y: f64::MAX,
        };
        let mut max = Pos {
            x: f64::MIN,
            y: f64::MIN,
        };
        let mut tool = None;
        let mut current_pos = Pos::default();
        let mut interp_mode = InterpolationMode::Linear;
        let mut quadrant = QuadrantMode::Multi;

        for command in self.commands.iter() {
            match command {
                Command::FunctionCode(FunctionCode::DCode(DCode::SelectAperture(ap))) => {
                    if let Some(ap) = self.apertures.get(ap) {
                        tool = Some(ap.get_corners());
                    }
                }
                Command::FunctionCode(FunctionCode::GCode(GCode::InterpolationMode(mode))) => {
                    interp_mode = *mode;
                }
                Command::FunctionCode(FunctionCode::GCode(GCode::QuadrantMode(mode))) => {
                    quadrant = *mode;
                }
                Command::FunctionCode(FunctionCode::DCode(DCode::Operation(op))) => match op {
                    Operation::Move(Some(coords)) => {
                        update_pos(&mut current_pos, coords, unit);
                        // Include move targets so stroke starts are bounded (no tool: not drawing).
                        min_max(&mut min, &mut max, coords, unit, &None);
                    }
                    Operation::Flash(Some(coords)) => {
                        update_pos(&mut current_pos, coords, unit);
                        min_max(&mut min, &mut max, coords, unit, &tool);
                    }
                    Operation::Interpolate(Some(end_coords), Some(offset))
                        if interp_mode != InterpolationMode::Linear =>
                    {
                        let start = current_pos.clone();
                        update_pos(&mut current_pos, end_coords, unit);
                        let (arc_min, arc_max) =
                            arc_corners(&start, &current_pos, offset, unit, interp_mode, quadrant);
                        let default = (Pos::default(), Pos::default());
                        let (tool_min, tool_max) = tool.as_ref().unwrap_or(&default);
                        min.x = min.x.min(arc_min.x + tool_min.x);
                        min.y = min.y.min(arc_min.y + tool_min.y);
                        max.x = max.x.max(arc_max.x + tool_max.x);
                        max.y = max.y.max(arc_max.y + tool_max.y);
                    }
                    Operation::Interpolate(Some(coords), _) => {
                        update_pos(&mut current_pos, coords, unit);
                        min_max(&mut min, &mut max, coords, unit, &tool);
                    }
                    _ => {}
                },
                _ => {}
            }
        }
        (min, max)
    }
}

impl LayerCorners for Aperture {
    fn get_corners(&self) -> (Pos, Pos) {
        // Minimum aperture size (mm) to include in bounding box calculations.
        // Thin traces/lines are excluded so they don't inflate board dimensions.
        const MIN_TOOL_SIZE: f64 = 0.1;
        let (x_size, y_size) = match self {
            Aperture::Circle(c) => (c.diameter, c.diameter),
            Aperture::Obround(r) | Aperture::Rectangle(r) => (r.x, r.y),
            Aperture::Polygon(_) | Aperture::Macro(_, _) => (0.0, 0.0),
        };
        if x_size < MIN_TOOL_SIZE && y_size < MIN_TOOL_SIZE {
            return (Pos::default(), Pos::default());
        }
        let (x, y) = (x_size / 2.0, y_size / 2.0);
        (Pos { x: -x, y: -y }, Pos { x, y })
    }
}

impl LayerTransform for (&Unit, &mut Vec<Command>) {
    fn transform(&mut self, transform: &Pos) {
        let (unit, cmds) = self;
        let to_unit = |x: f64| CoordinateNumber::try_from(x.mm_to_unit(unit)).ok();
        let to_mm = |x: &CoordinateNumber| f64::from(*x).to_mm(unit);
        for command in cmds.iter_mut() {
            if let Command::FunctionCode(FunctionCode::DCode(DCode::Operation(
                Operation::Move(Some(coords))
                | Operation::Flash(Some(coords))
                | Operation::Interpolate(Some(coords), _),
            ))) = command
            {
                if let Some(x) = coords.x {
                    coords.x = to_unit(to_mm(&x) + transform.x);
                }
                if let Some(y) = coords.y {
                    coords.y = to_unit(to_mm(&y) + transform.y);
                }
            }
        }
    }
}

impl LayerScale for (&CoordinateFormat, &mut Vec<Command>) {
    fn scale(&mut self, x: f64, y: f64) {
        let (format, cmds) = self;
        for cmd in cmds.iter_mut() {
            if let Command::FunctionCode(FunctionCode::DCode(DCode::Operation(op))) = cmd {
                match op {
                    Operation::Interpolate(Some(pos), _)
                    | Operation::Move(Some(pos))
                    | Operation::Flash(Some(pos)) => {
                        pos.scale(x, y);
                        pos.format = **format;
                    }
                    _ => {}
                }
                if let Operation::Interpolate(_, Some(pos)) = op {
                    pos.scale(x, y);
                    pos.format = **format;
                }
            }
        }
    }
}

macro_rules! coord_scaling {
    ($name:ident) => {
        impl LayerScale for $name {
            fn scale(&mut self, x: f64, y: f64) {
                self.x = self.x.map(|v| {
                    CoordinateNumber::try_from(f64::from(v) * x)
                        .expect("coordinate overflow: scale factor too large")
                });
                self.y = self.y.map(|v| {
                    CoordinateNumber::try_from(f64::from(v) * y)
                        .expect("coordinate overflow: scale factor too large")
                });
            }
        }
    };
}

